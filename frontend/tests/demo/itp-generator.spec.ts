import { expect, test } from "@playwright/test"

/*
 * Increment 17 — the public ITP generator (PRD v2.63 Block 10D) against the
 * clickable demo build (canned draft, see src/demo/fakeGenerator.ts). No
 * account: describe the work, get a watermarked draft with its PDF and JSON,
 * and see the limits and checks. Phone size.
 */

test.use({ viewport: { width: 412, height: 915 } })

test("scope → watermarked draft → PDF and JSON downloads", async ({ page }) => {
  await page.goto("/demo.html?start=/itp-generator")
  await expect(page.getByTestId("generator-form")).toBeVisible()
  const submit = page.getByTestId("generator-submit")
  await expect(submit).toBeDisabled()
  await expect(page.getByTestId("generator-counter")).toHaveText(
    "At least 20 characters",
  )

  // An example fills the box; an email needs the consent box.
  await page
    .getByTestId("generator-example")
    .getByText("Underground conduit")
    .click()
  await expect(page.getByTestId("generator-scope")).toHaveValue(/duct bank/)
  await expect(submit).toBeEnabled()
  await page.getByTestId("generator-email").fill("lead@example.com")
  await expect(submit).toBeDisabled()
  await page.getByTestId("generator-consent").click()
  await expect(submit).toBeEnabled()
  await submit.click()

  // The draft, watermarked, with its lines and flagged project values.
  const watermark = page.getByTestId("generator-watermark")
  await expect(watermark).toContainText(
    "Draft — generated by VR Inspector; review before use.",
  )
  await expect(watermark).toContainText("no claim of engineering adequacy")
  await expect(page.getByTestId("generator-draft")).toContainText(
    "16 lines · 1 hold point",
  )
  await expect(page.getByTestId("generator-section")).toHaveCount(5)
  await expect(page.getByTestId("generator-line")).toHaveCount(16)
  await expect(
    page
      .getByTestId("generator-line")
      .filter({ hasText: "Duct bank released" }),
  ).toContainText("Photo required")
  await expect(
    page
      .getByTestId("generator-line")
      .filter({ hasText: "Trench depth" })
      .getByText("Project-specific value required — verify before issue"),
  ).toBeVisible()
  await expect(page.getByTestId("generator-notes")).toContainText(
    "Confirm every value",
  )
  await expect(page.getByTestId("generator-pdf")).toHaveAttribute(
    "href",
    /sample-generator/,
  )

  // JSON download carries the watermark and reads as a template.
  const download = page.waitForEvent("download")
  await page.getByTestId("generator-json").click()
  const file = await download
  expect(file.suggestedFilename()).toMatch(
    /^draft-itp-concrete-encased.*\.json$/,
  )
  const path = await file.path()
  const { readFile } = await import("node:fs/promises")
  const json = JSON.parse(await readFile(path, "utf8"))
  expect(json.watermark).toBe(
    "Draft — generated by VR Inspector; review before use.",
  )
  expect(json.pages).toHaveLength(5)
  expect(json.importedWithAi).toBeUndefined()

  await expect(page.getByTestId("generator-cta")).toContainText(
    "Run it on site with VR Inspector",
  )

  // A new draft starts over.
  await page.getByTestId("generator-again").click()
  await expect(page.getByTestId("generator-form")).toBeVisible()
})

test("limits and a link that does not exist", async ({ page }) => {
  await page.goto(
    "/demo.html?start=/itp-generator?d=00000000-0000-4000-8000-000000000000",
  )
  await expect(page.getByTestId("generator-gone")).toContainText(
    "Draft not found",
  )
  await page.getByRole("link", { name: "Start a new draft" }).click()
  const scope = page.getByTestId("generator-scope")
  for (let n = 1; n <= 3; n++) {
    await scope.fill(
      `Pour a concrete footing number ${n}, 4 ft square, 2 ft deep.`,
    )
    await page.getByTestId("generator-submit").click()
    await expect(page.getByTestId("generator-draft")).toBeVisible()
    await page.getByTestId("generator-again").click()
  }
  await scope.fill("Pour a fourth concrete footing, 4 ft square.")
  await page.getByTestId("generator-submit").click()
  await expect(page.getByTestId("generator-error")).toContainText(
    "free limit of 3 drafts in an hour",
  )
})
