/*
 * Increment 17 — the public ITP generator (PRD v2.63 Block 10D). No account:
 * a visitor describes a scope of work and gets a draft ITP back as a page, a
 * PDF and a JSON template, every one watermarked "Draft — generated by VR
 * Inspector; review before use." Linked from vrinspector.com as the lead
 * magnet; outside the signed-in shell like the signing page. `?d=<id>`
 * reopens a draft (the random id is the only handle).
 */
type Search = { d?: string }

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

export const Route = createFileRoute("/itp-generator")({
  component: GeneratorPage,
  validateSearch: (search: Record<string, unknown>): Search =>
    typeof search.d === "string" && UUID.test(search.d) ? { d: search.d } : {},
  head: () => ({ meta: [{ title: "Free ITP generator - VR Inspector" }] }),
})

function GeneratorPage() {
  const { d } = Route.useSearch()
  return (
    <div className="min-h-svh bg-vri-offwhite text-vri-charcoal">
      <header className="border-b-4 border-vri-gold bg-vri-green px-4 py-3">
        <div className="mx-auto flex max-w-3xl items-center justify-between gap-3">
          <Logo variant="full" className="text-lg" asLink={false} />
          <span className="text-right text-xs uppercase tracking-widest text-vri-gold">
            Free ITP generator
          </span>
        </div>
      </header>
      <main className="mx-auto flex max-w-3xl flex-col gap-5 px-4 py-6">
        {d ? <DraftLoader publicId={d} /> : <GeneratorForm />}
      </main>
    </div>
  )
}

// --- the form ---------------------------------------------------------------------

function GeneratorForm() {
  const status = useQuery(generatorStatusQuery())
  if (status.isPending) {
    return <p className="py-16 text-center text-muted-foreground">Loading…</p>
  }
  if (status.isError || !status.data.enabled) {
    return (
      <div
        className="mx-auto flex max-w-md flex-col items-center gap-3 py-12 text-center"
        data-testid="generator-off"
      >
        <Sparkles className="size-10 text-vri-copper" aria-hidden />
        <h1 className="font-heading text-2xl text-vri-green">
          The free generator is resting
        </h1>
        <p className="text-muted-foreground">
          It is not available right now. Please try again later.
        </p>
      </div>
    )
  }
  return <ScopeForm status={status.data} />
}

function ScopeForm({ status }: { status: PublicItpGeneratorStatus }) {
  const navigate = useNavigate()
  const queryClient = useQueryClient()
  const [scope, setScope] = useState("")
  const [email, setEmail] = useState("")
  const [consent, setConsent] = useState(false)
  const [website, setWebsite] = useState("") // honeypot: people never see it
  const [error, setError] = useState<string | null>(null)

  const counter = scopeCounter(
    scope,
    status.min_scope_chars,
    status.max_scope_chars,
  )
  const emailNeedsConsent = email.trim() !== "" && !consent

  const generate = useMutation({
    mutationFn: async () =>
      (
        await GeneratorService.generateDraft({
          body: {
            scope,
            email: email.trim() || null,
            email_consent: consent,
            website: website || null,
          },
        })
      ).data as PublicItpDraft,
    onSuccess: (draft) => {
      queryClient.setQueryData(generatorKeys.draft(draft.public_id), draft)
      navigate({ to: "/itp-generator", search: { d: draft.public_id } })
      window.scrollTo({ top: 0 })
    },
    onError: (e: Error) => {
      const retry =
        e instanceof AxiosError && e.response?.status === 429
          ? waitText(Number(e.response.headers?.["retry-after"]))
          : null
      setError(`${extractErrorMessage(e)}${retry ? ` (wait ${retry})` : ""}`)
    },
  })

  const submit = (event: FormEvent) => {
    event.preventDefault()
    setError(null)
    generate.mutate()
  }

  return (
    <>
      <section className="flex flex-col gap-2">
        <p className="text-xs font-semibold uppercase tracking-widest text-vri-copper">
          No account needed
        </p>
        <h1 className="font-heading text-3xl text-vri-green">
          Draft an inspection and test plan in a minute
        </h1>
        <p>
          Describe the work. VR Inspector drafts an ITP — the stages, each check
          with a measurable acceptance criterion, its reference and record, hold
          and witness points and who signs them — as a PDF and a template you
          can edit.
        </p>
      </section>

      <form
        onSubmit={submit}
        className="flex flex-col gap-4 rounded-lg border border-border bg-white p-4 shadow-xs"
        data-testid="generator-form"
      >
        <div className="flex flex-col gap-2">
          <Label htmlFor="scope">Scope of work</Label>
          <Textarea
            id="scope"
            value={scope}
            onChange={(e) => setScope(e.target.value)}
            maxLength={status.max_scope_chars + 200}
            rows={6}
            className="min-h-36 text-base"
            placeholder="What is being built or installed, how much, and where. For example: 300 ft of concrete-encased duct bank from the substation to the MCC building, with pull boxes and backfill."
            data-testid="generator-scope"
          />
          <div className="flex flex-wrap items-center justify-between gap-2">
            <div className="flex flex-wrap gap-2">
              {EXAMPLE_SCOPES.map((example) => (
                <Button
                  key={example.label}
                  type="button"
                  size="sm"
                  variant="outline"
                  onClick={() => setScope(example.scope)}
                  data-testid="generator-example"
                >
                  {example.label}
                </Button>
              ))}
            </div>
            <span
              className={cn(
                "text-xs",
                counter.ok ? "text-muted-foreground" : "text-vri-brick",
              )}
              data-testid="generator-counter"
            >
              {counter.label}
            </span>
          </div>
        </div>

        <div className="flex flex-col gap-2">
          <Label htmlFor="generator-email">
            Email{" "}
            <span className="font-normal text-muted-foreground">
              (optional)
            </span>
          </Label>
          <Input
            id="generator-email"
            type="email"
            autoComplete="email"
            value={email}
            onChange={(e) => setEmail(e.target.value)}
            placeholder="you@company.com"
            data-testid="generator-email"
          />
          <div className="flex items-start gap-2">
            <Checkbox
              id="generator-consent"
              checked={consent}
              onCheckedChange={(v) => setConsent(v === true)}
              data-testid="generator-consent"
            />
            <Label
              htmlFor="generator-consent"
              className="text-sm font-normal leading-snug"
            >
              VR Inspector may keep my email and contact me about this draft and
              the app. Nothing is sent to it automatically.
            </Label>
          </div>
          {emailNeedsConsent ? (
            <p className="text-xs text-vri-brick">
              Tick the box to leave your email, or clear it.
            </p>
          ) : null}
        </div>

        {/* Honeypot: hidden from people and screen readers; bots fill it. */}
        <div
          aria-hidden="true"
          className="absolute -left-[9999px] h-0 overflow-hidden"
        >
          <label htmlFor="generator-website">Website</label>
          <input
            id="generator-website"
            tabIndex={-1}
            autoComplete="off"
            value={website}
            onChange={(e) => setWebsite(e.target.value)}
          />
        </div>

        {error ? (
          <p
            className="rounded-md border border-vri-brick/40 bg-vri-brick/5 px-3 py-2 text-sm text-vri-brick"
            role="alert"
            data-testid="generator-error"
          >
            {error}
          </p>
        ) : null}

        <LoadingButton
          type="submit"
          size="lg"
          loading={generate.isPending}
          disabled={!counter.ok || emailNeedsConsent}
          data-testid="generator-submit"
        >
          <Sparkles />
          {generate.isPending
            ? "Drafting — about half a minute…"
            : "Draft my ITP"}
        </LoadingButton>
        <p className="text-xs text-muted-foreground">
          Free: {status.hourly_limit} drafts an hour, {status.daily_limit} a
          day. {status.disclaimer}
        </p>
      </form>
    </>
  )
}

// --- the draft ----------------------------------------------------------------------

function DraftLoader({ publicId }: { publicId: string }) {
  const draft = useQuery(generatorDraftQuery(publicId))
  if (draft.isPending) {
    return (
      <p className="py-16 text-center text-muted-foreground">
        Opening your draft…
      </p>
    )
  }
  if (draft.isError) {
    return (
      <div
        className="mx-auto flex max-w-md flex-col items-center gap-3 py-12 text-center"
        data-testid="generator-gone"
      >
        <AlertTriangle className="size-10 text-vri-copper" aria-hidden />
        <h1 className="font-heading text-2xl text-vri-green">
          This draft can't be opened
        </h1>
        <p className="text-muted-foreground">
          {draft.error instanceof AxiosError &&
          draft.error.response?.status === 404
            ? extractErrorMessage(draft.error)
            : "Check your connection and try again."}
        </p>
        <Button asChild>
          <Link to="/itp-generator">Start a new draft</Link>
        </Button>
      </div>
    )
  }
  return <DraftView draft={draft.data} />
}

const VERIFY = "verify before issue"

function DraftView({ draft }: { draft: PublicItpDraft }) {
  const name = draft.draft.name || "Draft ITP"
  let number = 0
  return (
    <>
      <div
        className="flex gap-3 rounded-lg border-2 border-vri-brick bg-vri-brick/5 p-3"
        role="note"
        data-testid="generator-watermark"
      >
        <AlertTriangle
          className="mt-0.5 size-5 shrink-0 text-vri-brick"
          aria-hidden
        />
        <div className="text-sm">
          <p className="font-semibold text-vri-brick">{draft.watermark}</p>
          <p className="mt-1">{draft.disclaimer}</p>
        </div>
      </div>

      <section className="flex flex-col gap-1" data-testid="generator-draft">
        <p className="text-xs font-semibold uppercase tracking-widest text-vri-copper">
          Draft ITP · {draft.line_count} line{draft.line_count === 1 ? "" : "s"}{" "}
          · {draft.hold_count} hold point{draft.hold_count === 1 ? "" : "s"}
        </p>
        <h1 className="font-heading text-2xl text-vri-green">{name}</h1>
        {draft.draft.description ? <p>{draft.draft.description}</p> : null}
        <p className="text-xs text-muted-foreground">
          Generated {formatDate(draft.created_at)} · this link works until{" "}
          {formatDate(draft.expires_at)}
        </p>
      </section>

      <div className="flex flex-wrap gap-2">
        {draft.pdf_url ? (
          <Button asChild data-testid="generator-pdf">
            <a
              href={draft.pdf_url}
              target="_blank"
              rel="noreferrer"
              download={draftFileName(name, "pdf")}
            >
              <FileDown />
              Download PDF
            </a>
          </Button>
        ) : null}
        <Button
          variant="outline"
          onClick={() =>
            downloadJson(draft.template, draftFileName(name, "json"))
          }
          data-testid="generator-json"
        >
          <FileJson />
          Download template (JSON)
        </Button>
        <Button variant="ghost" asChild data-testid="generator-again">
          <Link to="/itp-generator">
            <RotateCcw />
            New draft
          </Link>
        </Button>
      </div>

      <details className="rounded-md border border-border bg-white px-3 py-2 text-sm">
        <summary className="cursor-pointer font-medium">Your scope</summary>
        <p className="mt-2 whitespace-pre-wrap text-muted-foreground">
          {draft.scope}
        </p>
      </details>

      {draft.draft.notes?.length ? (
        <section
          className="rounded-md border-l-4 border-vri-gold bg-white px-3 py-2"
          data-testid="generator-notes"
        >
          <h2 className="font-heading text-lg text-vri-green">
            Assumptions and things to check
          </h2>
          <ul className="mt-1 list-disc pl-5 text-sm">
            {draft.draft.notes.map((note) => (
              <li key={note}>{note}</li>
            ))}
          </ul>
        </section>
      ) : null}

      <p className="text-sm">
        <span className="font-semibold">Signed by: </span>
        {(draft.draft.roles ?? []).map((r) => r.name).join(" · ")}
      </p>

      {(draft.draft.sections ?? []).map((section) => (
        <section
          key={section.title}
          className="overflow-hidden rounded-lg border border-border bg-white"
          data-testid="generator-section"
        >
          <h2 className="bg-vri-green px-3 py-2 font-heading text-lg text-vri-offwhite">
            {section.title}
          </h2>
          <ol className="divide-y divide-border">
            {(section.lines ?? []).map((line) => {
              number += 1
              return <DraftLine key={number} number={number} line={line} />
            })}
          </ol>
        </section>
      ))}

      <section
        className="flex flex-col gap-2 rounded-lg border-2 border-vri-gold bg-white p-4"
        data-testid="generator-cta"
      >
        <h2 className="font-heading text-xl text-vri-green">
          Run it on site with VR Inspector
        </h2>
        <p className="text-sm">
          Turn the draft into a live ITP: Pass / Fail / N/A on a phone, photos
          on every line, hold points locked until released, sign-off links for
          the owner's representative and inspectors — and every check pinned to
          the drawing.
        </p>
        <div>
          <Button asChild variant="secondary">
            <Link to="/login">Sign in to VR Inspector</Link>
          </Button>
        </div>
      </section>
    </>
  )
}

function DraftLine({ number, line }: { number: number; line: ImportLine }) {
  const criteria = line.acceptance_criteria ?? ""
  return (
    <li className="flex gap-3 px-3 py-3" data-testid="generator-line">
      <div className="flex w-8 shrink-0 flex-col items-center gap-1">
        <span className="font-mono text-xs text-muted-foreground">
          {number}
        </span>
        <ClassificationChip value={line.classification ?? "I"} />
      </div>
      <div className="flex min-w-0 flex-col gap-1 text-sm">
        <p className="font-semibold">{line.title}</p>
        {criteria ? (
          <p>
            <span className="text-muted-foreground">Criterion: </span>
            <span
              className={cn(
                criteria.includes(VERIFY) && "font-medium text-vri-brick",
              )}
            >
              {criteria}
            </span>
          </p>
        ) : null}
        {line.reference ? (
          <p>
            <span className="text-muted-foreground">Reference: </span>
            {line.reference}
          </p>
        ) : null}
        {line.record_required ? (
          <p>
            <span className="text-muted-foreground">Record: </span>
            {line.record_required}
          </p>
        ) : null}
        <div className="flex flex-wrap gap-x-3 gap-y-1 text-xs text-muted-foreground">
          {line.roles?.length ? (
            <span>Signed by {line.roles.join(", ")}</span>
          ) : null}
          {line.photo_required ? (
            <span className="inline-flex items-center gap-1">
              <Camera className="size-3.5" aria-hidden /> Photo required
            </span>
          ) : null}
          {line.value_type && line.value_type !== "none" ? (
            <span className="inline-flex items-center gap-1">
              <Hash className="size-3.5" aria-hidden />
              Records a {line.value_type === "number" ? "number" : "value"}
              {line.unit ? ` (${line.unit})` : ""}
            </span>
          ) : null}
        </div>
      </div>
    </li>
  )
}
