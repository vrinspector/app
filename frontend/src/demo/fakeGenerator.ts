/*
 * Demo build only: the public ITP generator (increment 17; Block 10D).
 *
 * No server and no model: any scope long enough is answered with one canned,
 * plausible draft (a concrete-encased duct bank, `generatorSample.json`) and
 * the matching PDF rendered by the real API (`assets/sample-generator.pdf`),
 * so the owner can walk scope → draft → downloads. The demo keeps the same
 * input checks and a small in-memory hourly limit so the refusal shows too.
 */
import type { ItpImportDraft, PublicItpDraft } from "@/client"
import { draftToBody } from "@/lib/itpImport"

import sample from "./generatorSample.json"

type Body = Record<string, unknown>
type Handler = (args: {
  params: string[]
  query: URLSearchParams
  body: Body
}) => unknown

interface GeneratorDeps {
  on: (method: string, pattern: string, handler: Handler) => void
  fail: (status: number, detail: string) => never
  pdfUrl: string
}

export const WATERMARK = "Draft — generated by VR Inspector; review before use."
const DISCLAIMER =
  "This is an AI-generated starting point, not an engineered document. It makes no claim of engineering adequacy or code compliance. A competent person must check every line, criterion and reference against the project's drawings, specifications and governing codes before it is issued or used."
const MIN = 20
const MAX = 2000
const HOURLY = 3
const DAILY = 10
const KEEP_DAYS = 30

export function registerGeneratorRoutes({ on, fail, pdfUrl }: GeneratorDeps) {
  const drafts = new Map<string, PublicItpDraft>()
  const sent: number[] = []

  on("GET", "/public/itp-generator/status", () => ({
    enabled: true,
    watermark: WATERMARK,
    disclaimer: DISCLAIMER,
    min_scope_chars: MIN,
    max_scope_chars: MAX,
    hourly_limit: HOURLY,
    daily_limit: DAILY,
  }))

  on("POST", "/public/itp-generator", ({ body }) => {
    if (String(body.website ?? "").trim())
      fail(422, "This request could not be sent")
    const scope = String(body.scope ?? "")
      .split("\n")
      .map((line) => line.split(/\s+/).filter(Boolean).join(" "))
      .join("\n")
      .replace(/\n{3,}/g, "\n\n")
      .trim()
    if (scope.length < MIN)
      fail(
        422,
        "Describe the work in a sentence or two (what, where, how much)",
      )
    if (scope.length > MAX) fail(422, `Keep the scope under ${MAX} characters`)
    if (String(body.email ?? "").trim() && body.email_consent !== true)
      fail(422, "Tick the box to let us keep your email, or leave it blank")
    const now = Date.now()
    while (sent.length && sent[0] < now - 3600_000) sent.shift()
    if (sent.length >= HOURLY)
      fail(
        429,
        `You have reached the free limit of ${HOURLY} drafts in an hour. Try again later, or sign in to VR Inspector for more.`,
      )
    sent.push(now)

    const draft = structuredClone(sample) as ItpImportDraft
    const lines = (draft.sections ?? []).flatMap((s) => s.lines ?? [])
    const publicId = crypto.randomUUID()
    const created = new Date(now)
    const result: PublicItpDraft = {
      public_id: publicId,
      created_at: created.toISOString(),
      expires_at: new Date(now + KEEP_DAYS * 86_400_000).toISOString(),
      scope,
      draft,
      template: {
        watermark: WATERMARK,
        disclaimer: DISCLAIMER,
        generatedBy: "VR Inspector public ITP generator",
        ...draftToBody(draft, draft.name || "Draft ITP"),
      },
      watermark: WATERMARK,
      disclaimer: DISCLAIMER,
      model: "claude-sonnet-4-5 (demo — canned answer)",
      line_count: lines.length,
      hold_count: lines.filter((l) => l.classification === "H").length,
      pdf_url: pdfUrl,
    }
    delete (result.template as Record<string, unknown>).importedWithAi
    drafts.set(publicId, result)
    return result
  })

  on("GET", "/public/itp-generator/{public_id}", ({ params }) => {
    const draft = drafts.get(params[0])
    if (!draft) fail(404, "Draft not found")
    return draft
  })
}
