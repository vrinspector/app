"""Public ITP generator (Block 10D, rebuild increment 17).

PRD v2.63 §6: "Scope description → draft ITP (JSON + PDF) on vrinspector.com
with no account. Rate-limited, usage logged, output watermarked 'Draft —
generated by VR Inspector; review before use.' Optional email capture. No
claim of engineering adequacy."

This module holds everything about the generator that is not the model call
(``app.core.ai.AiService.generate_itp``) or the HTTP route
(``app.api.routes.public_itp``):

* **visitors** — the address a request came from, honouring
  ``PUBLIC_ITP_TRUSTED_PROXY_HOPS`` proxies, reduced to a keyed hash
  (:func:`visitor_key`). The address itself is never stored.
* **limits** — :func:`check_limits` counts the visitor's drafts in the last
  hour and day, and everyone's drafts today, from the usage log itself
  (``public_itp_generations``), so every worker sees the same counts.
* **output** — the watermarked template body for the JSON download
  (:func:`template_body`) and the watermarked PDF (:func:`render_pdf`, the
  same WeasyPrint path as reports and sign-off packs). The PDF is rendered
  once and kept in S3 under ``public/itp-generator/``.
"""

from __future__ import annotations

import hashlib
import hmac
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

from fastapi import Request
from jinja2 import Environment, FileSystemLoader, select_autoescape
from sqlmodel import Session, col, func, select

from app.core.config import settings
from app.core.itp_import import ItpImportDraft, draft_to_body
from app.core.reports import html_to_pdf
from app.models import PublicItpGeneration

WATERMARK = "Draft — generated by VR Inspector; review before use."
DISCLAIMER = (
    "This is an AI-generated starting point, not an engineered document. It "
    "makes no claim of engineering adequacy or code compliance. A competent "
    "person must check every line, criterion and reference against the "
    "project's drawings, specifications and governing codes before it is "
    "issued or used."
)

TEMPLATE_DIR = Path(__file__).resolve().parent.parent / "report-templates"
TEMPLATE_NAME = "public_itp.html"
S3_PREFIX = "public/itp-generator"

CLASSIFICATION_LABELS = {
    "H": "Hold point",
    "W": "Witness point",
    "R": "Review",
    "I": "Information",
}


# --- visitors ------------------------------------------------------------------


def client_address(request: Request) -> str:
    """The visitor's address: the socket peer, or — behind N trusted proxies —
    the Nth entry from the right of ``X-Forwarded-For`` (entries further left
    are written by the client and can be anything)."""
    peer = request.client.host if request.client else "unknown"
    hops = settings.PUBLIC_ITP_TRUSTED_PROXY_HOPS
    if hops <= 0:
        return peer
    forwarded = [
        part.strip()
        for part in request.headers.get("x-forwarded-for", "").split(",")
        if part.strip()
    ]
    if len(forwarded) >= hops:
        return forwarded[-hops]
    return forwarded[0] if forwarded else peer


def _salt() -> bytes:
    if settings.PUBLIC_ITP_IP_SALT:
        return settings.PUBLIC_ITP_IP_SALT.encode()
    # Stable across workers and restarts, secret like the database password.
    return hashlib.sha256(
        b"vri-public-itp|" + str(settings.DATABASE_URL).encode()
    ).digest()


def visitor_key(address: str) -> str:
    """A keyed hash of the address (64 hex characters); not reversible
    without the key, the same for one address across workers."""
    return hmac.new(_salt(), address.encode(), hashlib.sha256).hexdigest()


# --- limits --------------------------------------------------------------------


@dataclass
class LimitHit:
    detail: str
    retry_after: int  # seconds


def _count(session: Session, since: datetime, key: str | None = None) -> int:
    stmt = (
        select(func.count())
        .select_from(PublicItpGeneration)
        .where(col(PublicItpGeneration.created_at) >= since)
    )
    if key is not None:
        stmt = stmt.where(PublicItpGeneration.visitor_key == key)
    return int(session.exec(stmt).one())


def _oldest(session: Session, since: datetime, key: str) -> datetime | None:
    stmt = (
        select(func.min(PublicItpGeneration.created_at))
        .where(col(PublicItpGeneration.created_at) >= since)
        .where(PublicItpGeneration.visitor_key == key)
    )
    value: datetime | None = session.exec(stmt).one()
    return value


def check_limits(
    session: Session, key: str, now: datetime | None = None
) -> LimitHit | None:
    """``None`` when the visitor may have another draft now."""
    now = now or datetime.now(UTC)
    for window, limit, word in (
        (timedelta(hours=1), settings.PUBLIC_ITP_PER_IP_HOURLY, "an hour"),
        (timedelta(days=1), settings.PUBLIC_ITP_PER_IP_DAILY, "a day"),
    ):
        if limit <= 0:
            continue
        since = now - window
        if _count(session, since, key) >= limit:
            oldest = _oldest(session, since, key) or now
            wait = int((oldest + window - now).total_seconds()) + 1
            return LimitHit(
                f"You have reached the free limit of {limit} drafts in {word}. "
                "Try again later, or sign in to VR Inspector for more.",
                max(wait, 1),
            )
    ceiling = settings.PUBLIC_ITP_GLOBAL_DAILY
    if ceiling > 0:
        midnight = datetime.combine(now.date(), datetime.min.time(), tzinfo=UTC)
        if _count(session, midnight) >= ceiling:
            tomorrow = midnight + timedelta(days=1)
            return LimitHit(
                "The free generator has reached today's limit. Please try "
                "again tomorrow.",
                max(int((tomorrow - now).total_seconds()), 1),
            )
    return None


def clean_scope(scope: str) -> str:
    """Tidy spaces but keep paragraph breaks."""
    lines = [" ".join(line.split()) for line in scope.replace("\r", "").split("\n")]
    out: list[str] = []
    for line in lines:
        if line or (out and out[-1]):
            out.append(line)
    return "\n".join(out).strip()


def expires_at(row: PublicItpGeneration) -> datetime:
    created = row.created_at or datetime.now(UTC)
    return created + timedelta(days=settings.PUBLIC_ITP_KEEP_DAYS)


# --- output --------------------------------------------------------------------


def counts(draft: ItpImportDraft) -> tuple[int, int]:
    lines = [line for section in draft.sections for line in section.lines]
    return len(lines), sum(1 for line in lines if line.classification == "H")


def template_body(draft: ItpImportDraft) -> dict[str, Any]:
    """The JSON download: the same template body an import saves (so it can
    be pasted into VR Inspector as a template), marked as a generated draft."""
    body = draft_to_body(draft, name=draft.name or "Draft ITP")
    body.pop("importedWithAi", None)
    return {
        "watermark": WATERMARK,
        "disclaimer": DISCLAIMER,
        "generatedBy": "VR Inspector public ITP generator",
        **body,
    }


_env = Environment(
    loader=FileSystemLoader(str(TEMPLATE_DIR)),
    autoescape=select_autoescape(["html"]),
)


def render_html(row: PublicItpGeneration, draft: ItpImportDraft) -> str:
    line_count, hold_count = counts(draft)
    sections = []
    number = 0
    for section in draft.sections:
        lines = []
        for line in section.lines:
            number += 1
            lines.append(
                {
                    "number": number,
                    "code": line.classification,
                    "label": CLASSIFICATION_LABELS[line.classification],
                    "title": line.title,
                    "criteria": line.acceptance_criteria,
                    "reference": line.reference,
                    "record": line.record_required,
                    "roles": line.roles,
                    "photo": line.photo_required,
                    "value": (
                        f"Record a {'number' if line.value_type == 'number' else 'value'}"
                        + (f" ({line.unit})" if line.unit else "")
                        if line.value_type != "none"
                        else None
                    ),
                }
            )
        sections.append({"title": section.title, "lines": lines})
    created = row.created_at or datetime.now(UTC)
    return _env.get_template(TEMPLATE_NAME).render(
        title=draft.name or "Draft ITP",
        description=draft.description,
        scope=row.scope,
        roles=[{"name": r.name, "party": r.party} for r in draft.roles],
        sections=sections,
        notes=draft.notes,
        line_count=line_count,
        hold_count=hold_count,
        watermark=WATERMARK,
        disclaimer=DISCLAIMER,
        generated_at=created.astimezone(UTC).strftime("%b %d, %Y %H:%M UTC"),
        reference=str(row.public_id)[:8].upper(),
        app_url=settings.app_public_url,
    )


def render_pdf(row: PublicItpGeneration, draft: ItpImportDraft) -> bytes:
    return html_to_pdf(render_html(row, draft))


def pdf_key(row: PublicItpGeneration) -> str:
    return f"{S3_PREFIX}/{row.public_id}.pdf"
