"""Public ITP generator — no account (rebuild increment 17; PRD v2.63 Block 10D).

    GET  /public/itp-generator/status        → what the page needs to show
    POST /public/itp-generator  {scope, email?, email_consent?}
                                             → 201 the watermarked draft
    GET  /public/itp-generator/{public_id}   → the same draft again (for
                                               PUBLIC_ITP_KEEP_DAYS days)

No sign-in: the draft's random ``public_id`` (UUID4) is the only handle, the
way a signing link is. The guardrails the PRD asks for:

* **rate-limited** — per visitor per hour and per day, plus a daily ceiling
  for everyone (``app.core.public_itp.check_limits``); a refused request
  answers 429 with ``Retry-After``. A hidden form field catches simple bots
  before anything is counted or sent to the model.
* **usage logged** — every request that is let through is a
  ``public_itp_generations`` row (prompts, prompt / model version, tokens,
  draft or error); the address is kept only as a keyed hash.
* **watermarked** — the page, the JSON download and every page of the PDF
  carry "Draft — generated by VR Inspector; review before use." and the
  no-engineering-adequacy disclaimer.
* **optional email** — kept only with the consent box ticked; nothing is
  sent to it (a public form that emails any address it is given is a spam
  relay).
"""

import logging
import uuid
from datetime import UTC, datetime
from typing import Any

from fastapi import APIRouter, HTTPException, Request, Response, status
from sqlalchemy import text
from sqlmodel import Session, select

from app.api.deps import SessionDep
from app.core import ai as ai_core
from app.core import public_itp as pub
from app.core.ai import AiError, ai
from app.core.config import settings
from app.core.itp_import import ItpImportDraft
from app.core.storage import storage
from app.models import (
    PublicItpDraft,
    PublicItpGenerateRequest,
    PublicItpGeneration,
    PublicItpGeneratorStatus,
)

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/public/itp-generator", tags=["generator"])

# One advisory lock serialises "count, then reserve a row" so parallel
# requests from one visitor cannot slip past the limits together.
_LIMIT_LOCK = 0x56524954_5047  # "VRITPG"


@router.get("/status", response_model=PublicItpGeneratorStatus)
def read_status() -> Any:
    return PublicItpGeneratorStatus(
        enabled=settings.public_itp_enabled,
        watermark=pub.WATERMARK,
        disclaimer=pub.DISCLAIMER,
        min_scope_chars=settings.PUBLIC_ITP_MIN_SCOPE_CHARS,
        max_scope_chars=settings.PUBLIC_ITP_MAX_SCOPE_CHARS,
        hourly_limit=settings.PUBLIC_ITP_PER_IP_HOURLY,
        daily_limit=settings.PUBLIC_ITP_PER_IP_DAILY,
    )


def _ensure_pdf(
    session: Session, row: PublicItpGeneration, draft: ItpImportDraft
) -> str | None:
    """Render the watermarked PDF once, keep it in S3, hand out a short link."""
    if row.pdf_s3_key is None:
        try:
            pdf = pub.render_pdf(row, draft)
            key = pub.pdf_key(row)
            storage.put_object(key, pdf, "application/pdf")
        except Exception:  # noqa: BLE001 - the page works without the PDF
            logger.exception("Public ITP PDF could not be rendered")
            return None
        row.pdf_s3_key = key
        session.add(row)
        session.commit()
        session.refresh(row)
    return storage.presign_get(row.pdf_s3_key)


def _public(session: Session, row: PublicItpGeneration) -> PublicItpDraft:
    draft = ItpImportDraft.model_validate(row.draft or {})
    line_count, hold_count = pub.counts(draft)
    assert row.public_id is not None and row.created_at is not None
    return PublicItpDraft(
        public_id=row.public_id,
        created_at=row.created_at,
        expires_at=pub.expires_at(row),
        scope=row.scope,
        draft=draft,
        template=pub.template_body(draft),
        watermark=pub.WATERMARK,
        disclaimer=pub.DISCLAIMER,
        model=row.model,
        line_count=line_count,
        hold_count=hold_count,
        pdf_url=_ensure_pdf(session, row, draft),
    )


@router.post("", response_model=PublicItpDraft, status_code=status.HTTP_201_CREATED)
def generate_draft(
    payload: PublicItpGenerateRequest,
    request: Request,
    response: Response,
    session: SessionDep,
) -> Any:
    if not settings.public_itp_enabled:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="The free ITP generator is not available right now",
        )
    if (payload.website or "").strip():
        # A field people never see was filled in: a form-filling bot.
        raise HTTPException(status_code=422, detail="This request could not be sent")
    scope = pub.clean_scope(payload.scope)
    if len(scope) < settings.PUBLIC_ITP_MIN_SCOPE_CHARS:
        raise HTTPException(
            status_code=422,
            detail="Describe the work in a sentence or two (what, where, how much)",
        )
    if len(scope) > settings.PUBLIC_ITP_MAX_SCOPE_CHARS:
        raise HTTPException(
            status_code=422,
            detail=(
                f"Keep the scope under {settings.PUBLIC_ITP_MAX_SCOPE_CHARS} characters"
            ),
        )
    email = str(payload.email).strip().lower() if payload.email else None
    if email and not payload.email_consent:
        raise HTTPException(
            status_code=422,
            detail="Tick the box to let us keep your email, or leave it blank",
        )

    key = pub.visitor_key(pub.client_address(request))
    user_prompt = ai_core.generator_user_prompt(scope)
    session.connection().execute(
        text("SELECT pg_advisory_xact_lock(:key)"), {"key": _LIMIT_LOCK}
    )
    hit = pub.check_limits(session, key)
    if hit is not None:
        session.rollback()
        raise HTTPException(
            status_code=status.HTTP_429_TOO_MANY_REQUESTS,
            detail=hit.detail,
            headers={"Retry-After": str(hit.retry_after)},
        )
    # Reserve the row (it counts against the limits from now on), then let
    # the lock go before the slow model call.
    row = PublicItpGeneration(
        status="failed",
        error="in progress",
        visitor_key=key,
        scope=scope,
        email=email,
        email_consent_at=datetime.now(UTC) if email else None,
        user_agent=(request.headers.get("user-agent") or "")[:255] or None,
        model=settings.AI_MODEL,
        prompt_version=ai_core.ITP_GENERATOR_PROMPT_VERSION,
        system_prompt=ai_core.ITP_GENERATOR_SYSTEM_PROMPT,
        user_prompt=user_prompt,
    )
    session.add(row)
    session.commit()
    session.refresh(row)

    try:
        result = ai.generate_itp(user_prompt)
    except AiError as exc:
        row.error = exc.detail
        row.model = exc.model or row.model
        session.add(row)
        session.commit()
        raise HTTPException(status_code=exc.status_code, detail=exc.detail) from exc
    row.status = "draft"
    row.error = None
    row.model = result.model
    row.draft = result.draft
    row.input_tokens = result.input_tokens
    row.output_tokens = result.output_tokens
    session.add(row)
    session.commit()
    session.refresh(row)
    response.headers["Cache-Control"] = "no-store"
    return _public(session, row)


@router.get("/{public_id}", response_model=PublicItpDraft)
def read_draft(public_id: uuid.UUID, response: Response, session: SessionDep) -> Any:
    row = session.exec(
        select(PublicItpGeneration).where(PublicItpGeneration.public_id == public_id)
    ).first()
    if row is None or row.status != "draft" or not row.draft:
        raise HTTPException(status_code=404, detail="Draft not found")
    if pub.expires_at(row) < datetime.now(UTC):
        raise HTTPException(
            status_code=404,
            detail="This draft has expired; generate a new one",
        )
    response.headers["Cache-Control"] = "no-store"
    return _public(session, row)
