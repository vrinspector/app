def test_pdf_html_carries_the_watermark_disclaimer_and_lines() -> None:
    draft = ItpImportDraft.model_validate(GENERATOR_ANSWER).tidy()
    row = PublicItpGeneration(
        status="draft",
        visitor_key="k",
        scope="Pour a <slab> & cure it",
        model="m",
        prompt_version="v",
        system_prompt="s",
        user_prompt="u",
        created_at=datetime(2026, 11, 13, 7, 0, tzinfo=UTC),
    )
    row.public_id = uuid.UUID("12345678-0000-4000-8000-000000000000")
    html = pub.render_html(row, draft)
    assert html.count(pub.WATERMARK) >= 3  # running head, notice, footer
    assert str(escape(pub.DISCLAIMER)) in html
    assert ">DRAFT<" in html
    assert "Pour a &lt;slab&gt; &amp; cure it" in html  # escaped
    assert "Reinforcement placement and clear cover" in html
    assert 'class="verify"' in html  # flagged project-specific values
    assert "Record a number (in)" in html
    assert "draft 12345678" in html
    assert "Nov 13, 2026 07:00 UTC" in html


