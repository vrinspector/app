@pytest.mark.parametrize(
    ("setup", "code"),
    [("fail", 502), ("busy", 503), ("timeout", 502), ("no_tool", 502)],
)
def test_model_failures_are_logged_and_counted(
    client: TestClient,
    claude: FakeClaude,
    db: Session,
    monkeypatch: pytest.MonkeyPatch,
    setup: str,
    code: int,
) -> None:
    monkeypatch.setattr(settings, "PUBLIC_ITP_PER_IP_HOURLY", 1)
    if setup == "fail":
        claude.fail_with = 500
    elif setup == "busy":
        claude.fail_with = 429
    elif setup == "timeout":
        claude.timeout = True
    else:
        claude.no_tool = True
    r = _generate(client)
    assert r.status_code == code
    row = _rows(db)[0]
    assert row.status == "failed"
    assert row.error and row.error != "in progress"
    assert row.draft is None
    # A failed call still costs, so it still counts.
    assert _generate(client).status_code == 429
    # And a failed draft has no public page.
    assert client.get(f"{URL}/{row.public_id}").status_code == 404


