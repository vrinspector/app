def _request(peer: str, forwarded: str | None) -> Request:
    headers = [(b"x-forwarded-for", forwarded.encode())] if forwarded else []
    return Request(
        {"type": "http", "client": (peer, 1234), "headers": headers, "method": "GET"}
    )


def test_client_address(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(settings, "PUBLIC_ITP_TRUSTED_PROXY_HOPS", 0)
    assert pub.client_address(_request("10.0.0.1", "1.2.3.4")) == "10.0.0.1"
    monkeypatch.setattr(settings, "PUBLIC_ITP_TRUSTED_PROXY_HOPS", 1)
    assert pub.client_address(_request("10.0.0.1", "7.7.7.7, 1.2.3.4")) == "1.2.3.4"
    assert pub.client_address(_request("10.0.0.1", None)) == "10.0.0.1"
    monkeypatch.setattr(settings, "PUBLIC_ITP_TRUSTED_PROXY_HOPS", 2)
    assert pub.client_address(_request("10.0.0.1", "7.7.7.7, 1.2.3.4")) == "7.7.7.7"
    # Fewer entries than proxies: the leftmost there is.
    assert pub.client_address(_request("10.0.0.1", "1.2.3.4")) == "1.2.3.4"
    no_client = Request({"type": "http", "headers": [], "method": "GET"})
    monkeypatch.setattr(settings, "PUBLIC_ITP_TRUSTED_PROXY_HOPS", 0)
    assert pub.client_address(no_client) == "unknown"


