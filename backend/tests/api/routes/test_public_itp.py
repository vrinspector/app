@pytest.mark.usefixtures("claude")
def test_forwarded_address_counts_only_behind_a_trusted_proxy(
    client: TestClient, monkeypatch: pytest.MonkeyPatch, db: Session
) -> None:
    monkeypatch.setattr(settings, "PUBLIC_ITP_PER_IP_HOURLY", 1)
    # No trusted proxy: a made-up X-Forwarded-For changes nothing.
    assert _generate(client, headers={"X-Forwarded-For": "1.1.1.1"}).status_code == 201
    assert _generate(client, headers={"X-Forwarded-For": "2.2.2.2"}).status_code == 429
    # Behind one proxy, the proxy's entry (rightmost) is the visitor.
    monkeypatch.setattr(settings, "PUBLIC_ITP_TRUSTED_PROXY_HOPS", 1)
    assert (
        _generate(client, headers={"X-Forwarded-For": "9.9.9.9, 3.3.3.3"}).status_code
        == 201
    )
    # Spoofing the left-hand entries does not reset the count.
    assert (
        _generate(client, headers={"X-Forwarded-For": "8.8.8.8, 3.3.3.3"}).status_code
        == 429
    )
    assert _generate(client, headers={"X-Forwarded-For": "4.4.4.4"}).status_code == 201
    keys = [r.visitor_key for r in _rows(db)]
    assert keys == [
        pub.visitor_key("testclient"),
        pub.visitor_key("3.3.3.3"),
        pub.visitor_key("4.4.4.4"),
    ]


