def _rows(db: Session) -> list[PublicItpGeneration]:
    db.expire_all()
    return list(db.exec(select(PublicItpGeneration).order_by("id")).all())


def _generate(client: TestClient, **extra: Any) -> Any:
    headers = extra.pop("headers", None)
    return client.post(URL, json={"scope": SCOPE, **extra}, headers=headers)


