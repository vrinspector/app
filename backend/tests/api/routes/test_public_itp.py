@pytest.mark.usefixtures("claude")
def test_generate_returns_a_watermarked_draft_with_no_account(
    client: TestClient, fake_s3: FakeS3, db: Session
) -> None:
    r = _generate(client)
    assert r.status_code == 201, r.text
    assert r.headers["cache-control"] == "no-store"
    body = r.json()
    assert body["watermark"] == pub.WATERMARK
    assert body["disclaimer"] == pub.DISCLAIMER
    assert body["model"] == MODEL_VERSION
    assert body["scope"] == SCOPE
    draft = body["draft"]
    assert draft["name"] == GENERATOR_ANSWER["name"]
    assert [s["title"] for s in draft["sections"]] == [
        "Before work",
        "Pre-pour",
        "Placement",
    ]
    assert body["line_count"] == 4
    assert body["hold_count"] == 1
    # A hold point with no signer gets the owner's side and a note to check.
    hold = draft["sections"][1]["lines"][0]
    assert hold["classification"] == "H"
    assert hold["roles"] == ["Owner's representative"]
    assert any("named no signer" in n for n in draft["notes"])
    # Project-specific numbers stay flagged, not invented.
    assert (
        draft["sections"][0]["lines"][1]["acceptance_criteria"]
        == "Project-specific value required — verify before issue"
    )
    # JSON download: watermarked, and readable as a VR Inspector template.
    template = body["template"]
    assert template["watermark"] == pub.WATERMARK
    assert template["disclaimer"] == pub.DISCLAIMER
    assert "importedWithAi" not in template
    parsed = parse_template_body(template)
    assert len(parsed.items) == 4
    # The PDF is rendered once and kept in S3; the page gets a signed link.
    row = _rows(db)[0]
    assert row.pdf_s3_key == f"public/itp-generator/{row.public_id}.pdf"
    data, content_type = fake_s3.objects[row.pdf_s3_key]
    assert content_type == "application/pdf"
    assert data.startswith(b"%PDF")
    assert body["pdf_url"].startswith("https://")
    assert row.pdf_s3_key in body["pdf_url"]
    expires = datetime.fromisoformat(body["expires_at"])
    created = datetime.fromisoformat(body["created_at"])
    assert expires - created == timedelta(days=settings.PUBLIC_ITP_KEEP_DAYS)


