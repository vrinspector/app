def test_read_back_by_link(client: TestClient, claude: FakeClaude, db: Session) -> None:
    first = _generate(client).json()
    r = client.get(f"{URL}/{first['public_id']}")
    assert r.status_code == 200
    again = r.json()
    assert again["draft"] == first["draft"]
    assert again["template"] == first["template"]
    assert len(claude.requests) == 1  # reading back never calls the model
    assert client.get(f"{URL}/00000000-0000-4000-8000-000000000000").status_code == 404
    assert client.get(f"{URL}/not-a-uuid").status_code == 422
    # Expired links are gone.
    row = _rows(db)[0]
    row.created_at = datetime.now(UTC) - timedelta(
        days=settings.PUBLIC_ITP_KEEP_DAYS + 1
    )
    db.add(row)
    db.commit()
    r = client.get(f"{URL}/{first['public_id']}")
    assert r.status_code == 404
    assert "expired" in r.json()["detail"]


